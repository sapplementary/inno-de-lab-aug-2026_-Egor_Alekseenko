"""
task 2
Напишите программу, которая запрашивает у
пользователя длину и ширину прямоугольника. После получения данных
программа должна вычислить и вывести на экран площадь этого
прямоугольника.
"""
length = int(input(f'Введите длину прямоугольника: '))
width = int(input(f'Введите ширину прямоугольника: '))

squre = length * width

print(f'Площадь прямоугольника: {squre}')

